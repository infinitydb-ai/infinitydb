#!/usr/bin/env bash
# Score every system whose runs are present in benchmarks/arena/results and write
# docs/LEADERBOARD.md. Everything here ran locally with no API key: InfinityDB
# variants, mem0 with infer=False, BM25 + bge-large hybrid.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
PY="${PYTHON:-python3}"
SYSTEMS=$(find benchmarks/arena/results -maxdepth 2 -name '*.jsonl' | xargs -n1 dirname | sort -u | xargs -n1 basename | grep -v scores | paste -sd, -)
echo "systems: $SYSTEMS"
"$PY" benchmarks/arena/score.py --systems "$SYSTEMS" --no-reader >/dev/null 2>&1
"$PY" - <<'PY2'
import json
rows = json.load(open("benchmarks/arena/results/scores/summary.json"))
agg = lambda d: d["aggregate"]
data = sorted(rows.items(), key=lambda kv: -agg(kv[1])["evidence_recall@k"])
lines = ["# Local leaderboard (zero credentials)", "",
         "Generated by `scripts/leaderboard.sh`. Every row ran on this machine with no API key:",
         "InfinityDB variants, mem0 with `infer=False`, and a BM25 + `bge-large` hybrid.",
         "LoCoMo, 1,986 questions, top-10, one shared scoring script.", "",
         "| # | system | recall@10 | answer-in-context | ctx tokens | ingest | p50 |",
         "|---|---|---|---|---|---|---|"]
for i, (name, row) in enumerate(data, 1):
    a = agg(row)
    lines.append(f"| {i} | **{name}** | {a['evidence_recall@k']:.4f} | {a['answer_in_context']:.4f} | "
                 f"{a['context_tokens_median']} | {a['ingest_seconds']:.2f} s | {a['latency_ms']['p50']:.2f} ms |")
lines += ["", "Not measured: Zep/Graphiti and TencentDB's LLM pipeline need a graph database plus an",
          "extraction model (`benchmarks/arena/competitor_check.py` says why). Gap, not a win.", ""]
open("docs/LEADERBOARD.md", "w").write("\n".join(lines))
print("\n".join(lines[6:]))
PY2
