-- ============================================================================
-- InfinityDB core engine schema for PostgreSQL 14+.
--
-- This is the Postgres twin of the SQLite DDL in infinitydb/core/engine.py.
-- PostgresEngineStore sets `search_path` to one schema per tenant before it runs
-- this file, so every unqualified table below is created inside that tenant's
-- schema. The engine's SQL never names a schema or a tenant: two tenants can hold
-- identical facts without colliding, and even a superuser connection only sees
-- the schema it is bound to.
--
-- Other differences from the SQLite DDL:
--   * `rid` replaces SQLite's implicit rowid (identity, stable for joins)
--   * `fact_tsv` / `window_tsv` are generated tsvectors with GIN indexes,
--     replacing the FTS5 virtual tables
--   * the window index uses `public.infinitydb_porter`, a no-stopword Snowball
--     configuration created by PostgresEngineStore.initialize(), because the
--     stock `english` configuration drops words FTS5 indexes
-- ============================================================================

CREATE TABLE IF NOT EXISTS l0_logs (
    id            TEXT PRIMARY KEY,
    user_id       TEXT NOT NULL,
    session_id    TEXT,
    raw           TEXT NOT NULL,
    metadata_json TEXT,
    ts            DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_l0_user_ts ON l0_logs(user_id, ts);

CREATE TABLE IF NOT EXISTS l1_atoms (
    id            TEXT PRIMARY KEY,
    user_id       TEXT NOT NULL,
    fact          TEXT NOT NULL,
    category      TEXT NOT NULL,
    source_id     TEXT NOT NULL,
    importance    DOUBLE PRECISION NOT NULL,
    access_count  INTEGER NOT NULL DEFAULT 0,
    ts            DOUBLE PRECISION NOT NULL,
    fact_tsv      tsvector GENERATED ALWAYS AS (
                      to_tsvector('simple', coalesce(fact, ''))
                  ) STORED
);
CREATE INDEX IF NOT EXISTS idx_l1_user_cat ON l1_atoms(user_id, category);
CREATE INDEX IF NOT EXISTS idx_l1_fact ON l1_atoms(fact);
CREATE INDEX IF NOT EXISTS idx_l1_fact_tsv_gin ON l1_atoms USING GIN (fact_tsv);

CREATE TABLE IF NOT EXISTS recall_feedback (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    TEXT NOT NULL,
    query      TEXT NOT NULL,
    query_stem TEXT NOT NULL,
    atom_id    TEXT NOT NULL,
    label      DOUBLE PRECISION NOT NULL,
    ts         DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_feedback_user ON recall_feedback(user_id, query_stem);

CREATE TABLE IF NOT EXISTS infinitydb_schema_meta (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS legacy_memories (
    memory_key TEXT PRIMARY KEY,
    content    TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS l2_episodes (
    id        TEXT PRIMARY KEY,
    user_id   TEXT NOT NULL,
    cause     TEXT NOT NULL,
    effect    TEXT NOT NULL,
    relation  TEXT NOT NULL,
    source_id TEXT NOT NULL,
    ts        DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_l2_user ON l2_episodes(user_id);

CREATE TABLE IF NOT EXISTS l3_persona (
    user_id        TEXT NOT NULL,
    key            TEXT NOT NULL,
    value          TEXT NOT NULL,
    confidence     DOUBLE PRECISION NOT NULL,
    source_atom_id TEXT,
    updated_at     DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (user_id, key)
);

CREATE TABLE IF NOT EXISTS l4_policies (
    id         TEXT PRIMARY KEY,
    rule       TEXT NOT NULL,
    domain     TEXT NOT NULL,
    priority   DOUBLE PRECISION NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    tenant_id  TEXT
);
CREATE INDEX IF NOT EXISTS idx_l4_domain ON l4_policies(domain);
CREATE INDEX IF NOT EXISTS idx_l4_tenant_priority ON l4_policies(tenant_id, priority DESC);

CREATE TABLE IF NOT EXISTS l1_atom_relations (
    old_atom_id TEXT NOT NULL,
    new_atom_id TEXT NOT NULL,
    user_id     TEXT NOT NULL,
    relation    TEXT NOT NULL CHECK (relation = 'supersedes'),
    created_at  DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (old_atom_id, new_atom_id),
    CHECK (old_atom_id <> new_atom_id)
);
CREATE INDEX IF NOT EXISTS idx_l1_relations_user_time
    ON l1_atom_relations(user_id, created_at);

CREATE TABLE IF NOT EXISTS l1_entity_edges (
    id         TEXT PRIMARY KEY,
    user_id    TEXT NOT NULL,
    session_id TEXT,
    atom_id    TEXT NOT NULL,
    subject    TEXT NOT NULL,
    predicate  TEXT NOT NULL,
    object     TEXT NOT NULL,
    ts         DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_l1_edges_subject ON l1_entity_edges(user_id, subject);
CREATE INDEX IF NOT EXISTS idx_l1_edges_object ON l1_entity_edges(user_id, object);

CREATE TABLE IF NOT EXISTS l1_turn_windows (
    rid         BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    atom_id     TEXT PRIMARY KEY,
    user_id     TEXT NOT NULL,
    session_id  TEXT,
    seq         INTEGER NOT NULL,
    turn_text   TEXT NOT NULL,
    window_text TEXT NOT NULL,
    ts          DOUBLE PRECISION NOT NULL,
    window_tsv  tsvector GENERATED ALWAYS AS (
                    to_tsvector('public.infinitydb_porter'::regconfig,
                                coalesce(window_text, ''))
                ) STORED
);
CREATE INDEX IF NOT EXISTS idx_l1_windows_user_seq
    ON l1_turn_windows(user_id, session_id, seq);
CREATE INDEX IF NOT EXISTS idx_l1_window_tsv_gin
    ON l1_turn_windows USING GIN (window_tsv);

CREATE TABLE IF NOT EXISTS l2_vectors (
    model        TEXT NOT NULL,
    window_rowid BIGINT NOT NULL REFERENCES l1_turn_windows(rid) ON DELETE CASCADE,
    dim          INTEGER NOT NULL,
    vec          BYTEA NOT NULL,
    PRIMARY KEY (model, window_rowid)
);

CREATE TABLE IF NOT EXISTS l6_proof (
    atom_id       TEXT PRIMARY KEY,
    hash          TEXT NOT NULL,
    source_log_id TEXT NOT NULL,
    raw_snippet   TEXT NOT NULL,
    char_start    INTEGER,
    char_end      INTEGER,
    ts            DOUBLE PRECISION NOT NULL
);
